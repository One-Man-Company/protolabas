let lang = 'lt';
let overlay = null;

export const i18n = {
  get lang() { return lang; },
  setLang(next) {
    lang = strings[next] ? next : 'lt';
    document.documentElement.lang = lang;
  },
  t(key, vars) {
    const table = strings[lang] || strings.lt;
    let out = table[key] ?? strings.lt[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, v);
    return out;
  },
  // Optional per-module translation overlay: { "<slug>": { title, tagline, activities: [...] } }
  setOverlay(data) { overlay = data || null; },
  module(m) {
    if (!overlay || !overlay[m.id] || lang === 'lt') return m;
    return { ...m, ...overlay[m.id] };
  },
  has(key) { return Boolean((strings[lang] || {})[key] ?? strings.lt[key]); }
};
